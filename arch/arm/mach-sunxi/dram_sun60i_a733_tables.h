#define PHY_BCAST_AC		BIT(30)
#define PHY_BCAST_9LANE		BIT(29)
#define PHY_BCAST_MASK		(PHY_BCAST_DBYTE | PHY_BCAST_AC | PHY_BCAST_9LANE)

